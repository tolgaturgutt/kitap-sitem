-- Normal profil guncellemelerinde rol, Premium bitis tarihi ve ban korumasi devam eder.
-- Yalnizca guvenli satin alma/sona erdirme islemleri korumali alanlari degistirebilir.
create or replace function public.protect_critical_profile_columns()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if exists (
    select 1
    from public.announcement_admins admin
    where lower(admin.user_email) =
      lower(coalesce(auth.jwt() ->> 'email', ''))
  ) then
    return new;
  end if;

  if current_setting('kitaplab.premium_purchase', true) = 'allowed'
    and new.id = auth.uid()
    and new.role = 'premium'
    and new.premium_expires_at > now()
    and new.is_banned is not distinct from old.is_banned
  then
    return new;
  end if;

  if current_setting('kitaplab.premium_expiration', true) = 'allowed'
    and old.role = 'premium'
    and old.premium_expires_at is not null
    and old.premium_expires_at <= now()
    and new.role = 'user'
    and new.premium_expires_at is null
    and new.is_banned is not distinct from old.is_banned
  then
    return new;
  end if;

  if new.role is distinct from old.role then
    new.role := old.role;
  end if;

  if new.premium_expires_at is distinct from old.premium_expires_at then
    new.premium_expires_at := old.premium_expires_at;
  end if;

  if new.is_banned is distinct from old.is_banned then
    new.is_banned := old.is_banned;
  end if;

  return new;
end;
$$;

create or replace function public.can_use_premium_features()
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $$
  select
    auth.uid() is not null
    and (
      exists (
        select 1
        from public.profiles profile
        where profile.id = auth.uid()
          and profile.role = 'premium'
          and (
            profile.premium_expires_at is null
            or profile.premium_expires_at > now()
          )
      )
      or exists (
        select 1
        from public.announcement_admins admin
        where lower(admin.user_email) =
          lower(coalesce(auth.jwt() ->> 'email', ''))
      )
    );
$$;

