  'Premium uyeligin bitis zamani. Yalnizca yormeci hesabi icin NULL suresiz uyelik anlamina gelir.';

-- Mevcut Premium hesaplari aylik sisteme tasir. Yilmaz'in hesabi suresiz kalir.
update public.profiles
set
  premium_expires_at = now() + interval '1 month',
  updated_at = now()
where role = 'premium'
  and id <> 'e3cd0953-1674-4a8a-a09d-676a9bcf367b'::uuid
  and premium_expires_at is null;

update public.profiles
set
  role = 'premium',
  premium_expires_at = null,
  updated_at = now()
where id = 'e3cd0953-1674-4a8a-a09d-676a9bcf367b'::uuid;

create table if not exists public.labcoin_transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  amount integer not null check (amount <> 0),
  transaction_type text not null,
  reference_key text not null,
  description text,
  created_at timestamptz not null default now(),
  unique (user_id, transaction_type, reference_key)
);

create index if not exists labcoin_transactions_user_time_idx
  on public.labcoin_transactions (user_id, created_at desc);

alter table public.labcoin_transactions enable row level security;

drop policy if exists "Users can view their LabCoin transactions"
on public.labcoin_transactions;
create policy "Users can view their LabCoin transactions"
on public.labcoin_transactions
for select
to authenticated
