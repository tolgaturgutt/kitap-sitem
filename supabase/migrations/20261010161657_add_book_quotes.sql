begin;

create schema if not exists quote_private;
revoke all on schema quote_private from public;

create or replace function quote_private.can_quote_book(target_book_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public, auth, pg_temp
as $$
  select auth.uid() is not null and exists (
    select 1
    from public.books book
    where book.id = target_book_id
      and coalesce(book.is_draft, false) = false
      and book.user_id is distinct from auth.uid()
      and not (
        book.co_author_id is not distinct from auth.uid()
        and coalesce(book.co_author_status = 'accepted', false)
      )
  );
$$;

create or replace function quote_private.is_published_quote_book(target_book_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.books book
    where book.id = target_book_id
      and coalesce(book.is_draft, false) = false
  );
$$;

revoke all on function quote_private.can_quote_book(bigint) from public;
revoke all on function quote_private.is_published_quote_book(bigint) from public;
grant usage on schema quote_private to anon, authenticated;
grant execute on function quote_private.can_quote_book(bigint) to authenticated;
grant execute on function quote_private.is_published_quote_book(bigint) to anon, authenticated;

create table if not exists public.book_quotes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  content text not null,
  is_pinned boolean not null default false,
  created_at timestamptz not null default now(),
  constraint book_quotes_content_length_check
    check (char_length(btrim(content)) between 3 and 1000)
);

create table if not exists public.quote_saves (
  quote_id bigint not null references public.book_quotes(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (quote_id, user_id)
);

create index if not exists book_quotes_created_at_idx
  on public.book_quotes (created_at desc);
create index if not exists book_quotes_book_id_idx
  on public.book_quotes (book_id);
create index if not exists book_quotes_user_id_idx
  on public.book_quotes (user_id);
create index if not exists quote_saves_user_id_idx
  on public.quote_saves (user_id);

alter table public.book_quotes enable row level security;
alter table public.quote_saves enable row level security;

drop policy if exists book_quotes_select_published on public.book_quotes;
create policy book_quotes_select_published
on public.book_quotes
for select
to anon, authenticated
using ((select quote_private.is_published_quote_book(book_id)));

drop policy if exists book_quotes_insert_other_books on public.book_quotes;
create policy book_quotes_insert_other_books
on public.book_quotes
for insert
to authenticated
with check (
  (select auth.uid()) = user_id
  and (select quote_private.can_quote_book(book_id))
);

drop policy if exists book_quotes_delete_own on public.book_quotes;
create policy book_quotes_delete_own
on public.book_quotes
for delete
to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists quote_saves_select_own on public.quote_saves;
create policy quote_saves_select_own
on public.quote_saves
for select
to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists quote_saves_insert_own on public.quote_saves;
create policy quote_saves_insert_own
on public.quote_saves
for insert
to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists quote_saves_delete_own on public.quote_saves;
create policy quote_saves_delete_own
on public.quote_saves
for delete
to authenticated
using ((select auth.uid()) = user_id);

revoke all on table public.book_quotes from public, anon, authenticated;
revoke all on table public.quote_saves from public, anon, authenticated;

grant select on table public.book_quotes to anon, authenticated;
grant insert, delete on table public.book_quotes to authenticated;
grant select, insert, delete on table public.quote_saves to authenticated;
grant usage, select on sequence public.book_quotes_id_seq to authenticated;

commit;

notify pgrst, 'reload schema';

select
  to_regclass('public.book_quotes') as book_quotes_table,
  to_regclass('public.quote_saves') as quote_saves_table,
  (
    select count(*)
    from pg_policies
    where schemaname = 'public'
      and tablename in ('book_quotes', 'quote_saves')
  ) as policy_count;
