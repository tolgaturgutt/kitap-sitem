begin;

create table if not exists public.quote_votes (
  id bigint generated by default as identity primary key,
  quote_id bigint not null references public.book_quotes(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (quote_id, user_id)
);

create table if not exists public.quote_comments (
  id bigint generated by default as identity primary key,
  quote_id bigint not null references public.book_quotes(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  content text not null,
  created_at timestamptz not null default now(),
  constraint quote_comments_content_length_check
    check (char_length(btrim(content)) between 1 and 1000)
);

alter table public.notifications
  add column if not exists quote_id bigint references public.book_quotes(id) on delete set null;

create index if not exists quote_votes_quote_id_idx on public.quote_votes (quote_id);
create index if not exists quote_votes_user_id_idx on public.quote_votes (user_id);
create index if not exists quote_comments_quote_created_idx on public.quote_comments (quote_id, created_at);
create index if not exists quote_comments_user_id_idx on public.quote_comments (user_id);
create index if not exists notifications_quote_id_idx on public.notifications (quote_id);

alter table public.quote_votes enable row level security;
alter table public.quote_comments enable row level security;

drop policy if exists quote_votes_select_public on public.quote_votes;
create policy quote_votes_select_public on public.quote_votes
for select to anon, authenticated
using (exists (select 1 from public.book_quotes quote where quote.id = quote_votes.quote_id));

drop policy if exists quote_votes_insert_own on public.quote_votes;
create policy quote_votes_insert_own on public.quote_votes
for insert to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists quote_votes_delete_own on public.quote_votes;
create policy quote_votes_delete_own on public.quote_votes
for delete to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists quote_comments_select_public on public.quote_comments;
create policy quote_comments_select_public on public.quote_comments
for select to anon, authenticated
using (exists (select 1 from public.book_quotes quote where quote.id = quote_comments.quote_id));

drop policy if exists quote_comments_insert_own on public.quote_comments;
create policy quote_comments_insert_own on public.quote_comments
for insert to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists quote_comments_delete_author_owner_admin on public.quote_comments;
create policy quote_comments_delete_author_owner_admin on public.quote_comments
for delete to authenticated
using (
  (select auth.uid()) = user_id
  or (select public.is_current_user_admin())
  or exists (
    select 1 from public.book_quotes quote
    where quote.id = quote_comments.quote_id and quote.user_id = (select auth.uid())
  )
);

revoke all on table public.quote_votes from public, anon, authenticated;
revoke all on table public.quote_comments from public, anon, authenticated;
grant select on table public.quote_votes, public.quote_comments to anon, authenticated;
grant insert, delete on table public.quote_votes, public.quote_comments to authenticated;
grant usage, select on sequence public.quote_votes_id_seq, public.quote_comments_id_seq to authenticated;

commit;

notify pgrst, 'reload schema';

select
  to_regclass('public.quote_votes') as quote_votes_table,
  to_regclass('public.quote_comments') as quote_comments_table,
  exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'notifications' and column_name = 'quote_id'
  ) as notification_link_installed;
